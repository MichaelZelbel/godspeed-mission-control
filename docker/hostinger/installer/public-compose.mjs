import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { IMAGE, CADDY } from './compose.mjs';

export const REGISTRATION_ENDPOINT = 'https://godspeedmissioncontrol.com/godspeed-install/api/servers/register';

// The public file identifies no buyer and contains no credential. Its server's
// secret is useful to the coordinator only after authenticated Hostinger API
// ownership proof; knowing a hostname or making the first visit never owns it.
export function registrationCode({ endpoint = REGISTRATION_ENDPOINT, hostnameFile = '/run/godspeed-vps-hostname' } = {}) {
  const url = new URL(endpoint);
  if (url.protocol !== 'https:' || url.username || url.password) throw new Error('Server registration requires HTTPS');
  return `const fs=require('fs');let h=fs.readFileSync(${JSON.stringify(hostnameFile)},'utf8').trim();if(/^srv[0-9]+$/.test(h))h+='.hstgr.cloud';if(!/^srv[0-9]+\\.hstgr\\.cloud$/.test(h))throw Error('Hostinger server address could not be detected');const setup=process.env.GODSPEED_ACCESS_TOKEN;if(!/^[a-f0-9]{64}$/.test(setup||''))throw Error('Private setup code could not be loaded');async function register(){let failures=0;for(;;){let renewed=false;try{const r=await fetch('http://127.0.0.1:47831/health',{redirect:'error',signal:AbortSignal.timeout(3000)});if(r.ok){const auth=await fetch('http://127.0.0.1:47831/api/auth/status',{redirect:'error',signal:AbortSignal.timeout(3000)});if(auth.ok){const state=await auth.json();if(state.configured===true)return;if(state.configured===false){const registered=await fetch(${JSON.stringify(url.href)},{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({hostname:h,setup}),redirect:'error',signal:AbortSignal.timeout(10000)});renewed=registered.status===202;}}}}catch{}if(renewed)failures=0;else failures++;const delay=renewed?1200000:Math.min(300000,5000*2**Math.min(failures-1,6));await new Promise(r=>setTimeout(r,delay));}}register();`;
}

export function publicCompose() {
  const setupFile = '/opt/data/full-candidate/.install-setup-code';
  const setup = `if [ ! -s ${setupFile} ]; then (umask 077; node -e 'process.stdout.write(require("crypto").randomBytes(32).toString("hex"))' > ${setupFile}); fi; GODSPEED_ACCESS_TOKEN=$$(cat ${setupFile}); export GODSPEED_ACCESS_TOKEN; `;
  const startup = `${setup}node -e ${shellQuote(registrationCode())} & exec /opt/godspeed/kit/docker/full-candidate/entrypoint.sh`;
  const rule = 'HostSNIRegexp(`^srv[0-9]+\\.hstgr\\.cloud$$`)';
  const https = `h=$$(cat /run/godspeed-vps-hostname | tr -d '\\r\\n'); printf '%s' "$$h" | grep -Eq '^srv[0-9]+(\\.hstgr\\.cloud)?$$' || { echo 'Hostinger server address could not be detected' >&2; exit 1; }; case "$$h" in *.hstgr.cloud) ;; *) h="$$h.hstgr.cloud";; esac; printf '%s\\n' '{' '  admin off' '}' "$$h {" '  tls {' '    issuer acme {' '      disable_http_challenge' '    }' '  }' '  reverse_proxy godspeed:47831' '}' > /tmp/godspeed-Caddyfile; exec caddy run --adapter caddyfile --config /tmp/godspeed-Caddyfile`;
  return `# Public Godspeed Mission Control installer for Hostinger Docker template 1210.
# Generated by node docker/hostinger/installer/public-compose.mjs.
# No buyer credentials or setup fields belong in this file.
# The server generates its own private code. The website releases account setup
# only after Hostinger confirms that the signed-in person owns this server.
name: godspeed-mission-control
services:
  godspeed:
    image: ${IMAGE}
    restart: unless-stopped
    init: true
    environment:
      GODSPEED_DEVICE: vps
      GODSPEED_COMPUTER: "off"
    entrypoint: ["/bin/sh", "-ec"]
    command:
      - ${JSON.stringify(startup)}
    volumes:
      - godspeed-data:/opt/data/full-candidate
      - /etc/hostname:/run/godspeed-vps-hostname:ro
    expose: ["47831"]
    logging:
      driver: json-file
      options: {max-size: "10m", max-file: "3"}
  https:
    image: ${CADDY}
    restart: unless-stopped
    entrypoint: ["/bin/sh", "-ec"]
    command:
      - ${JSON.stringify(https)}
    expose: ["443"]
    labels:
      traefik.enable: "true"
      traefik.tcp.routers.godspeed-mission-control.rule: ${JSON.stringify(rule)}
      traefik.tcp.routers.godspeed-mission-control.entrypoints: websecure
      traefik.tcp.routers.godspeed-mission-control.tls.passthrough: "true"
      traefik.tcp.routers.godspeed-mission-control.service: godspeed-mission-control
      traefik.tcp.services.godspeed-mission-control.loadbalancer.server.port: "443"
    volumes:
      - godspeed-certificates:/data
      - godspeed-proxy-config:/config
      - /etc/hostname:/run/godspeed-vps-hostname:ro
    depends_on:
      godspeed: {condition: service_healthy}
    logging:
      driver: json-file
      options: {max-size: "10m", max-file: "3"}
volumes:
  godspeed-data: {}
  godspeed-certificates: {}
  godspeed-proxy-config: {}
`;
}

function shellQuote(value) { return "'" + value.replace(/'/g, "'\\''") + "'"; }

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = new URL('../one-click.yaml', import.meta.url), expected = publicCompose();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== expected) { console.error('Public Hostinger manifest needs regeneration.'); process.exitCode = 1; }
  } else fs.writeFileSync(file, expected);
}
